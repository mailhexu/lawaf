MODE_KPTS = [
    (0.0, 0.0, 0.0),  # istwfk 2
    (0.5, 0.0, 0.0),  # 3
    (0.0, 0.0, 0.5),  # 4
    (0.5, 0.0, 0.5),  # 5
    (0.0, 0.5, 0.0),  # 6
    (0.5, 0.5, 0.0),  # 7
    (0.0, 0.5, 0.5),  # 8
    (0.5, 0.5, 0.5),  # 9
    (0.25, 0.125, 0.0),  # 1 (general point)
]


def _build_mode_fixture(tmp_path, ecut=3.0):
    """One synthetic file with one k per mode; full + packed coefficient refs."""
    gmet = (2.0 * np.pi) ** 2 / 100.0 * np.eye(3)  # rprimd = 10*I
    per_k, refs = [], []
    kpts = []
    for kpt in MODE_KPTS:
        kg_full = g_sphere(kpt, ecut, gmet)
        kg_stored, istwfk = packed_half(kpt, kg_full)
        kpts.append(kpt)
        stored_full_ref = coeff_reference(kpt, kg_stored)
        # full-storage reference coefficients on the FULL sphere
        full_ref = {}
        g0 = np.round(2 * np.asarray(kpt)).astype(int)
        for g, v in stored_full_ref.items():
            g_arr = np.array(g)
            p = tuple(-g_arr - g0)
            full_ref[g] = v
            if istwfk > 1 and p != g:
                full_ref[p] = np.conj(v)
        nband = 3
        cg_stored = np.array(
            [[stored_full_ref[tuple(g)] for g in kg_stored] for _ in range(nband)]
        )
        per_k.append(
            {
                "kg": kg_stored.T.copy(),
                "eig": np.linspace(-1, 1, nband),
                "cg": cg_stored,
            }
        )
        refs.append({"istwfk": istwfk, "kg_full": kg_full, "full_ref": full_ref})
    header = synthetic_header(kpts, [len(p["kg"][0]) for p in per_k], 3)
    path = tmp_path / "modes.wfk"
    write_binary_wfk(path, header, per_k)
    return path, header, refs


def test_060_02_decode_matches_full_storage_reference(tmp_path):
    path, header, refs = _build_mode_fixture(tmp_path)
    r = WfkReader.open(path)
    tol = 1e-12
    for ik, ref in enumerate(refs):
        kg_full, w_full, cg_full = r.decode_full_sphere(ik, 0, (0, 3))
        assert r.header.resolved_istwfk[ik] == ref["istwfk"]
        # full sphere matches the explicit full-storage reference
        keys_ref = {tuple(g) for g in ref["kg_full"]}
        keys_got = {tuple(g) for g in kg_full.T}
        assert keys_got == keys_ref
        order = {tuple(g): i for i, g in enumerate(kg_full.T)}
        for g, v in ref["full_ref"].items():
            for b in range(3):
                got = cg_full[b, order[g], 0]
                assert abs(got - v) <= tol * max(1.0, abs(v)), (ik, g, got, v)
        # norms equal full-storage reference: weights applied exactly once
        for b in range(3):
            ref_norm = sum(abs(v) ** 2 for v in ref["full_ref"].values())
            got_norm = float(np.sum(w_full * np.abs(cg_full[b, :, 0]) ** 2))
            assert abs(got_norm - ref_norm) <= 1e-12 * max(1.0, ref_norm)
        # double-weight mutation is detected (norms would differ)
        if header.resolved_istwfk[ik] > 1:
            doubled = float(np.sum((2 * w_full) * np.abs(cg_full[0, :, 0]) ** 2))
            ref_norm = sum(abs(v) ** 2 for v in ref["full_ref"].values())
            assert abs(doubled - ref_norm) > 1e-6
    r.close()


