def test_060_04_bounded_scratch_scaling(tmp_path):
    import gc
    import tracemalloc

    nband = 4
    peaks = {}
    for n in (4, 6, 8):
        kpts = []
        per_k = []
        rng = np.random.default_rng(n)
        ecut = 2.0
        gmet = (2.0 * np.pi) ** 2 / 100.0 * np.eye(3)
        for i in range(n):
            for j in range(n):
                for kk in range(n):
                    kpt = (i / n, j / n, kk / n)
                    kg = g_sphere(kpt, ecut, gmet)
                    kg = kg[np.abs(kg).max(axis=1) <= 2][:32]
                    assert len(kg) == 32
                    cg = rng.normal(size=(nband, len(kg), 1)) + 1j * rng.normal(
                        size=(nband, len(kg), 1)
                    )
                    per_k.append(
                        {"kg": kg.T.copy(), "eig": np.linspace(-1, 1, nband), "cg": cg}
                    )
                    kpts.append(kpt)
        header = synthetic_header(kpts, [len(p["kg"][0]) for p in per_k], nband)
        path = tmp_path / f"mesh{n}.wfk"
        write_binary_wfk(path, header, per_k)
        with WfkReader.open(path) as reader:
            gc.collect()
            tracemalloc.start()
            try:
                for ik in range(header.nkpt):
                    cg = reader.coefficients(ik, 0, (1, 3))
                    eig = reader.eigenvalues(ik, 0, (1, 3))
                    del cg, eig
                peaks[n] = tracemalloc.get_traced_memory()[1]
            finally:
                tracemalloc.stop()
            # Fixed block plus Python allocation overhead, independent of Nk.
            assert peaks[n] <= 16 * 1024
            print(
                f"MEASURE reader {n}^3: traced live scratch peak={peaks[n]} bytes; declared={reader.peak_live_bytes}"
            )
    assert max(peaks.values()) <= 1.5 * min(peaks.values()) + 2048


