@needs_scalar
def test_060_01_real_netcdf_header_and_eigen_parity():
    import netCDF4

    ref = netCDF4.Dataset(SCALAR_NC)
    r = WfkReader.open(SCALAR_BIN)
    h = r.header
    # Independent direct inspection of the NetCDF file of the same deck.
    assert h.codvsn == b"".join(ref["codvsn"][:]).decode().strip("\x00")
    assert h.nkpt == len(ref.dimensions["number_of_kpoints"])
    assert h.nsppol == len(ref.dimensions["number_of_spins"])
    assert h.nspinor == len(ref.dimensions["number_of_spinor_components"])
    assert h.nspden == 1
    assert h.usepaw == int(ref["usepaw"][:])
    np.testing.assert_array_equal(h.rprimd, ref["primitive_vectors"][:])
    np.testing.assert_allclose(
        h.kpt, ref["reduced_coordinates_of_kpoints"][:], atol=0, rtol=0
    )
    np.testing.assert_array_equal(h.resolved_istwfk, ref["istwfk"][:])
    np.testing.assert_array_equal(h.npwarr, ref["number_of_coefficients"][:])
    np.testing.assert_array_equal(h.symrel, ref["reduced_symmetry_matrices"][:])
    np.testing.assert_allclose(h.tnons, ref["reduced_symmetry_translations"][:])
    np.testing.assert_array_equal(h.symafm, ref["symafm"][:])
    np.testing.assert_array_equal(h.kptrlatt, ref["kptrlatt"][:])
    np.testing.assert_allclose(h.shiftk, ref["shiftk"][:])
    assert list(h.lmn_size) == [int(x) for x in ref["lmn_size"][:]]
    assert list(h.md5_pseudos) == [
        b"".join(row).decode().strip("\x00") for row in ref["md5_pseudos"][:]
    ]
    # eigen slab parity: bit-exact for energies as stored, no conversion
    for ispin in range(h.nsppol):
        for ik in range(h.nkpt):
            nb = h.nband[ik + ispin * h.nkpt]
            eig = r.eigenvalues(ik, ispin, (0, nb))
            ref_eig = np.array(ref["eigenvalues"][ispin, ik, :nb])
            assert np.array_equal(eig, ref_eig)
    # no eager coefficient read: eigen path must not touch coefficient records
    r.close()
    ref.close()


