def coeff_reference(kpt, kg):
    """Analytic stored coefficient field with known full-sphere reference."""
    g0 = np.round(2.0 * np.asarray(kpt, dtype=float)).astype(int)
    rng = np.random.default_rng(20261002)
    full = {}
    for g in np.asarray(kg):
        key = tuple(g)
        if key in full:
            continue
        full[key] = complex(rng.normal(), rng.normal())
    return full


class _RecWriter:
    """Fortran unformatted sequential records (4-byte markers)."""

    def __init__(self, path):
        self._fh = open(path, "wb")

    def record(self, payload):
        self._fh.write(struct.pack("<I", len(payload)))
        self._fh.write(payload)
        self._fh.write(struct.pack("<I", len(payload)))

    def close(self):
        self._fh.close()


def write_binary_wfk(path, header, per_k, formeig=0):
    """Write a real Fortran-record WFK.

    per_k: list over (k) of dicts with keys kg (3,npw), eig (nband),
    cg (nband, npw, nspinor) complex.
    """
    w = _RecWriter(path)
    w.record(
        struct.pack("<8sii", header.codvsn.encode(), header.headform, header.fform)
    )
    ints = [
        header.bantot,
        header.date,
        header.intxc,
        header.ixc,
        header.natom,
        *header.ngfft,
        header.nkpt,
        header.nspden,
        header.nspinor,
        header.nsppol,
        header.nsym,
        header.npsp,
        header.ntypat,
        header.occopt,
        header.pertcase,
        header.usepaw,
    ]
    reals = [header.ecut, header.ecutdg, header.ecutsm, header.ecut_eff]
    tail = [header.usewvl, header.nshiftk_orig, header.nshiftk, header.mband]
    payload = struct.pack(
        "<18i4d3d9d3d4i",
        *ints,
        *reals,
        *header.qptn,
        *header.rprimd.ravel(order="C"),
        header.stmbias,
        header.tphysel,
        header.tsmear,
        *tail,
    )
    w.record(payload)
    rec3 = b"".join(
        a.tobytes()
        for a in [
            header.istwfk.astype("<i4"),
            header.nband.astype("<i4"),
            header.npwarr.astype("<i4"),
            header.so_psp.astype("<i4"),
            header.symafm.astype("<i4"),
            header.symrel.ravel(order="F").astype("<i4"),
            header.typat.astype("<i4"),
            header.kpt.ravel(order="C").astype("<f8"),
            header.occ.ravel(order="F").astype("<f8"),
            header.tnons.ravel(order="F").astype("<f8"),
            np.asarray(header.znucltypat, dtype=float).astype("<f8"),
            header.wtk.astype("<f8"),
        ]
    )
    w.record(rec3)
    rec4 = b"".join(
        a.tobytes()
        for a in [
            np.array([header.residm], "<f8"),
            header.xred.ravel(order="C").astype("<f8"),
            np.array([header.etot, header.fermie], "<f8"),
            header.amu.astype("<f8"),
        ]
    )
    w.record(rec4)
    rec5 = b"".join(
        a.tobytes()
        for a in [
            np.array([header.kptopt, header.pawcpxocc], "<i4"),
            np.array([header.nelect, header.cellcharge], "<f8"),
            np.array([header.icoulomb], "<i4"),
            header.kptrlatt.ravel(order="F").astype("<i4"),
            header.kptrlatt_orig.ravel(order="F").astype("<i4"),
            header.shiftk_orig.ravel(order="C").astype("<f8"),
            header.shiftk.ravel(order="C").astype("<f8"),
        ]
    )
    w.record(rec5)
    for i in range(header.npsp):
        w.record(
            struct.pack(
                "<132s2d5i32s",
                header.title[i].encode().ljust(132)[:132],
                header.znuclpsp[i],
                header.zionpsp[i],
                header.pspso[i],
                header.pspdat[i],
                header.pspcod[i],
                header.pspxc[i],
                header.lmn_size[i],
                header.md5_pseudos[i].encode(),
            )
        )
    for k in range(header.nkpt):
        d = per_k[k]
        npw = d["kg"].shape[1]
        nband = header.nband[k]
        nspinor = header.nspinor
        w.record(struct.pack("<3i", npw, nspinor, nband))
        w.record(d["kg"].astype("<i4").ravel(order="F").tobytes())
        w.record(
            np.concatenate([d["eig"], np.zeros(nband)]).astype("<f8").tobytes()
            if formeig == 0
            else d["eig"].astype("<f8").tobytes()
        )
        for b in range(nband):
            cg = np.empty(2 * npw * nspinor, dtype="<f8")
            arr = d["cg"][b]
            # ABINIT cg(2,npw*nspinor): G varies fastest within each spinor.
            cg[0::2] = arr.real.ravel(order="F")
            cg[1::2] = arr.imag.ravel(order="F")
            w.record(cg.tobytes())
            if formeig == 1:
                w.record(np.zeros(nband, dtype="<f8").tobytes())
    w.close()


