def _kpoint_mode(kpt, tol=1e-10):
    """set_istwfk semantics (m_cgtools.F90:898-928), certified by epic-048-c."""
    bit0 = 1
    bits = [0, 0, 0]
    for i in range(3):
        if abs(kpt[i]) < tol:
            bits[i] = 0
        elif abs(kpt[i] - 0.5) < tol:
            bits[i] = 1
        else:
            bit0 = 0
    if bit0 == 0:
        return 1
    return 2 + bits[0] + 4 * bits[1] + 2 * bits[2]


def g_sphere(kpt, ecut, gmet):
    """Full G sphere at kpt: reduced ints with kinetic <= ecut (Hartree, 2pi/a)."""
    k = np.asarray(kpt, dtype=float)
    out = []
    nmax = int(np.ceil(np.sqrt(2.0 * ecut) * 1.5 + 2))
    for i in range(-nmax, nmax + 1):
        for j in range(-nmax, nmax + 1):
            for kk in range(-nmax, nmax + 1):
                g = np.array([i, j, kk])
                kin = 0.5 * (k + g) @ gmet @ (k + g)
                if kin <= ecut + 1e-12:
                    out.append(g)
    return np.array(out, dtype=np.int32)


def packed_half(kpt, kg_full):
    """Packed half-sphere: one representative per involution orbit.

    istwfk > 1: involution G -> -G - G0 with G0 = 2*k; at Gamma (istwfk == 2)
    G0 = 0.  Self-conjugate planes (2G == -G0) are kept once.
    """
    istwfk = _kpoint_mode(kpt)
    if istwfk == 1:
        return np.asarray(kg_full, dtype=np.int32).copy(), 1
    g0 = np.round(2.0 * np.asarray(kpt, dtype=float)).astype(int)
    kept = []
    seen = set()
    for g in kg_full:
        key = tuple(g)
        if key in seen:
            continue
        p = tuple(-g - g0)
        kept.append(g)
        seen.add(key)
        seen.add(p)
    return np.array(kept, dtype=np.int32), istwfk


