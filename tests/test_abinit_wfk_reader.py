@needs_soc
def test_060_03_spinor_energy_component_identity():
    import netCDF4

    r = WfkReader.open(SOC_NC)
    h = r.header
    assert (h.nsppol, h.nspinor, h.nspden) == (1, 2, 4)
    assert np.all(h.resolved_istwfk == 1)
    ref = netCDF4.Dataset(SOC_NC)
